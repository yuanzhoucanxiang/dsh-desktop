// Real pinned Harness + hidden Electron; fresh home, no keys, no model requests.
// Owns only the kernel process it starts. Never attaches to a user's desktop.
const { app, BrowserWindow } = require('electron')
const fs = require('node:fs')
const path = require('node:path')
const os = require('node:os')
const http = require('node:http')
const { spawn } = require('node:child_process')
const assert = require('node:assert/strict')
const repo = path.resolve(__dirname, '..')
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'dsh-writing-native-'))
const home = path.join(temp, 'home')
const root = path.join(temp, 'library')
const project = path.join(root, '灯塔来信')
const doc = path.join(project, 'draft/novel/第1章-v1.md')
app.setPath('userData', path.join(temp, 'user-data'))
const sleep = ms => new Promise(r => setTimeout(r, ms))
let kernel, win, kernelOutput = ''
const failures = [], results = []
app.whenReady().then(async () => {
  fs.mkdirSync(path.dirname(doc), { recursive: true })
  fs.mkdirSync(home, { recursive: true })
  fs.writeFileSync(doc, '灯塔的影子落在信封上。她没有拆开那封信。')
  fs.writeFileSync(path.join(project, 'project.md'), '作品名：灯塔来信')
  fs.writeFileSync(path.join(home, 'writing-mode.json'), JSON.stringify({ roots: [{ path: root, default: true }], activeRoot: root, prefs: { autoGate: false } }))
  fs.cpSync(path.join(repo, 'plugin/writing-mode'), path.join(home, 'profiles/node_modules/@dsh-local/writing-mode'), { recursive: true })
  const patch = path.join(temp, 'kernel.patch.yml')
  fs.writeFileSync(patch, '- insert:\n    - id: writing-mode\n      name: "@dsh-local/writing-mode"\n')
  const probe = http.createServer()
  await new Promise(r => probe.listen(0, '127.0.0.1', r))
  const port = probe.address().port
  await new Promise(r => probe.close(r))
  kernel = spawn(path.join(repo, 'runtime/node.exe'), [path.join(repo, 'runtime/node_modules/@deepseek-ai/dsh/lib/bin.js'), '--profile', 'web', '--patch', patch, '--port', String(port), '--no-open'], { cwd: project, env: { ...process.env, DSH_HOME: home }, windowsHide: true, stdio: ['ignore', 'pipe', 'pipe'] })
  kernel.stdout.on('data', d => { kernelOutput += d })
  kernel.stderr.on('data', d => { kernelOutput += d })
  const deadline = Date.now() + 90000
  let ready = false
  while (Date.now() < deadline && kernel.exitCode === null) {
    try { if ((await fetch(`http://127.0.0.1:${port}`, { signal: AbortSignal.timeout(1000) })).ok) { ready = true; break } } catch {}
    await sleep(150)
  }
  assert.ok(ready, kernelOutput)
  win = new BrowserWindow({ width: 1500, height: 1000, show: false, webPreferences: { backgroundThrottling: false } })
  win.webContents.on('console-message', (event, level, message) => {
    const d = event.message ? event : { level, message }
    if (d.level === 'error' || d.level === 3) failures.push(d.message)
  })
  const evaluate = code => win.webContents.executeJavaScript(code, true)
  async function waitFor(code) {
    const until = Date.now() + 15000
    while (Date.now() < until) { if (await evaluate(code)) return; await sleep(60) }
    throw new Error('Timed out: ' + code + '\n' + await evaluate('document.body.innerText'))
  }
  const button = text => evaluate(`(Array.from(document.querySelectorAll('.dshWmRoot button')).find(e=>e.textContent===${JSON.stringify(text)}) || Array.from(document.querySelectorAll('button')).find(e=>e.textContent===${JSON.stringify(text)}))?.click()`)
  await win.loadURL(`http://127.0.0.1:${port}`)
  await waitFor(`!!document.getElementById('dsh-writing-mode-float')`)
  await waitFor(`Array.from(document.querySelectorAll('button')).some(e=>e.textContent==='继续'&&!e.disabled)`)
  await button('继续')
  await waitFor(`!document.body.innerText.includes('内测声明')`)
  await waitFor(`Array.from(document.querySelectorAll('button')).some(e=>e.textContent==='稍后配置')`)
  await button('稍后配置')
  await waitFor(`!document.body.innerText.includes('添加一个 API Key')`)
  await evaluate(`document.getElementById('dsh-writing-mode-float').click()`)
  await waitFor(`!!document.querySelector('.dshWmItem')`)
  await evaluate(`document.querySelector('.dshWmItem').click()`)
  await waitFor(`document.querySelector('.dshWmEditor')?.value.includes('灯塔的影子')`)
  await waitFor(`!!document.querySelector('.dshWmChatInput')`)
  assert.equal(await evaluate(`!!document.querySelector('[data-writing-companion]')`), false)
  assert.equal(await evaluate(`document.querySelector('.dshWmCompanion').innerText.includes('探索未至之境')`), false)
  const input = text => evaluate(`(()=>{const el=document.querySelector('.dshWmChatInput');Object.getOwnPropertyDescriptor(HTMLTextAreaElement.prototype,'value').set.call(el,${JSON.stringify(text)});el.dispatchEvent(new Event('input',{bubbles:true}));})()`)
  await input('想听听你对她为什么不拆信的看法。')
  await button('会话设置 ↗')
  await waitFor(`!document.querySelector('.dshWmRoot')`)
  await button('稍后配置')
  const config = JSON.parse(fs.readFileSync(path.join(home, 'writing-mode.json'), 'utf8'))
  const sessionId = Object.values(config.companions)[0]
  await waitFor(`document.querySelector('[data-composer-seat] textarea')?.value==='想听听你对她为什么不拆信的看法。'`)
  await evaluate(`document.getElementById('dsh-writing-mode-float').click()`)
  await waitFor(`document.querySelector('.dshWmChatInput')?.value==='想听听你对她为什么不拆信的看法。'`)
  results.push('独立写作 UI / 原生项目会话 / 完整会话共享输入')
  console.log('PASS', results.at(-1))
  await evaluate(`document.querySelector('.dshWmEditor').setSelectionRange(0,5)`)
  await button('＋ 引用稿件 / 选区')
  await waitFor(`!!document.querySelector('.dshWmReference')`)
  const reference = await evaluate(`document.querySelector('.dshWmReference').textContent`)
  assert.ok(reference.includes('灯塔的影子'))
  assert.ok(!reference.includes('她没有拆开那封信。'))
  const draft = await evaluate(`document.querySelector('.dshWmChatInput').value`)
  assert.equal(draft, '想听听你对她为什么不拆信的看法。')
  for (const label of ['文字工具', '写作伙伴', '专注', '专注']) await button(label)
  await waitFor(`!!document.querySelector('.dshWmChatInput')`)
  assert.equal(await evaluate(`document.querySelector('.dshWmChatInput').value`), draft)
  assert.ok(await evaluate(`!!document.querySelector('.dshWmReference')`))
  await evaluate(`document.querySelector('[aria-label="移除稿件引用"]').click()`)
  await waitFor(`!document.querySelector('.dshWmReference')`)
  results.push('选区引用可移除；输入独立；切换工具与专注保留草稿和引用')
  console.log('PASS', results.at(-1))
  const restored = JSON.parse(fs.readFileSync(path.join(home, 'writing-mode.json'), 'utf8'))
  assert.equal(Object.values(restored.companions)[0], sessionId)
  const rects = await evaluate(`(()=>{const a=document.querySelector('.dshWmSide.is-ai').getBoundingClientRect(),b=document.querySelector('.dshWmCompose').getBoundingClientRect();return {inside:b.left>=a.left&&b.right<=a.right&&b.bottom<=a.bottom,width:b.width}})()`)
  assert.ok(rects.inside && rects.width > 250, JSON.stringify(rects))
  const cacheFile = path.join(home, 'storages/session_projcache.json')
  const cacheDeadline = Date.now() + 10000
  while (!fs.existsSync(cacheFile) && Date.now() < cacheDeadline) await sleep(100)
  const cache = JSON.parse(fs.readFileSync(cacheFile, 'utf8'))
  assert.equal(cache.tables.sessions[sessionId].rows.sessionStats.val.turns, 0)
  assert.deepEqual(failures, [])
  results.push('独立输入区在侧栏内；未产生模型回合；无控制台错误')
  console.log('PASS', results.at(-1))
  await button('继续')
  await sleep(250)
  fs.writeFileSync(path.join(temp, 'native.png'), (await win.webContents.capturePage()).toPNG())
  console.log('WRITING_NATIVE_OK', temp)
}).catch(err => { console.error(err); process.exitCode = 1 }).finally(async () => {
  fs.writeFileSync(path.join(temp, 'kernel.log'), kernelOutput)
  fs.writeFileSync(path.join(temp, 'results.json'), JSON.stringify({ passed: !process.exitCode, results, failures }, null, 2))
  if (win && !win.isDestroyed()) win.destroy()
  // Only this test's own background Node kernel, never Desktop/electron processes.
  if (kernel && kernel.exitCode === null) kernel.kill()
  app.exit(process.exitCode || 0)
})
