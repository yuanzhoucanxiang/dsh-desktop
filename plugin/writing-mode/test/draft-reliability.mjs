import fs from 'node:fs'
import path from 'node:path'
import os from 'node:os'
import assert from 'node:assert/strict'
import { writeCheckpoint, readCheckpoint, listCheckpoints, damagedCheckpointHash, recoverDamagedCheckpoint } from '../lib/draft-checkpoints.js'
import { relocationCandidates, recoverRelocation, relocationHistory } from '../lib/project-recovery.js'
import { claimCoordination, confirmCoordination, readCoordination } from '../lib/coordination.js'
import { emptyEtag, applyMemoryOp, readMemory } from '../lib/project-memory.js'
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'wm-draft-repair-'))
process.env.DSH_HOME = path.join(temp, 'home')
const old = path.join(temp, 'old')
const moved = path.join(temp, 'moved')
fs.mkdirSync(old); fs.writeFileSync(path.join(old, 'project.md'), 'test')
writeCheckpoint(old, 'broken', { baseRev: 0, text: 'draft' })
const dir = path.join(process.env.DSH_HOME, 'writing-mode/drafts')
const file = path.join(dir, fs.readdirSync(dir)[0])
const raw = '{"schemaVersion":2,"text":"recoverable original"'
fs.writeFileSync(file, raw)
assert.throws(() => readCheckpoint(old, 'broken'), /corrupt-draft/)
assert.throws(() => writeCheckpoint(old, 'broken', { baseRev: 0, text: 'replacement' }), /corrupt-draft/)
assert.equal(fs.readFileSync(file, 'utf8'), raw)
assert.throws(() => recoverDamagedCheckpoint(old, 'broken', { text: 'replacement' }, 'wrong'), /recovery-source-changed/)
const saved = recoverDamagedCheckpoint(old, 'broken', { text: 'replacement' }, damagedCheckpointHash(old, 'broken'))
assert.equal(fs.readFileSync(path.join(dir, saved.backup), 'utf8'), raw)
assert.equal(readCheckpoint(old, 'broken').text, 'replacement')
console.log('PASS D03 bad JSON blocked, stale recovery refused, exact damaged backup retained')
fs.writeFileSync(file, JSON.stringify({ schemaVersion: 2, text: 123, project: old, windowId: 'broken', rev: 1 }))
assert.throws(() => writeCheckpoint(old, 'broken', { baseRev: 0, text: 'bad' }), /corrupt-draft/)
recoverDamagedCheckpoint(old, 'broken', { text: 'recovered' }, damagedCheckpointHash(old, 'broken'))
console.log('PASS D03 malformed schema blocked')
applyMemoryOp(old, { op: 'save-setting-candidate', baseRevision: 0, baseEtag: emptyEtag(), clientSchemaVersion: 2, operationId: 'mark-test', item: { kind: 'fact', setting: { title: 'unresolved', conclusion: 'open', modelMark: 'open', pending: true } } })
assert.equal(readMemory(old).memory.items[0].setting.modelMark, 'open')
console.log('PASS D02 unresolved marker round-trip')
writeCheckpoint(old, 'chat', { baseRev: 0, text: 'unsent', reference: { text: 'quote', path: old } })
writeCheckpoint(old + '\0world', 'window', { baseRev: 0, text: JSON.stringify({ version: 1, drafts: [{ id: 'd', title: 'world', conclusion: 'draft' }] }) })
claimCoordination({ projectKey: old, operationToken: 'move' })
confirmCoordination({ projectKey: old, operationToken: 'move', sessionId: 'old-session' })
assert.equal(relocationCandidates(moved).length, 0)
fs.renameSync(old, moved)
const source = relocationCandidates(moved).find(c => c.oldPath === old)
assert.ok(source)
assert.throws(() => recoverRelocation(moved, old, 'wrong'), /recovery-source-changed/)
const r = recoverRelocation(moved, old, source.token)
assert.ok(r.copied >= 2)
assert.ok(listCheckpoints(moved).some(c => c.text === 'unsent' && c.reference.text === 'quote'))
assert.equal(listCheckpoints(moved + '\0world').length, 1)
assert.equal(relocationHistory(moved)[0].sessions[0], 'old-session')
assert.equal(readCoordination(moved).sessionId, null, 'Old native workspace is never silently rebound')
assert.equal(readCoordination(old).sessionId, 'old-session')
assert.equal(readMemory(moved).memory.items[0].setting.title, 'unresolved')
console.log('PASS D04 explicit relocation restores chat/world drafts and history links; current workspace stays isolated')
const imported = listCheckpoints(moved).find(c => c.text === 'unsent')
writeCheckpoint(moved, imported.windowId, { baseRev: imported.rev, text: 'edited after recovery' })
recoverRelocation(moved, old, source.token)
assert.equal(readCheckpoint(moved, imported.windowId).text, 'edited after recovery')
assert.ok(listCheckpoints(old).some(c => c.text === 'unsent'))
console.log('PASS D04 retry does not overwrite recovered edit; old buckets retained')
fs.mkdirSync(old)
assert.throws(() => recoverRelocation(moved, old, source.token), /recovery-source-changed/)
console.log('PASS D04 existing/copy source cannot be merged as a moved project')
console.log('DRAFT_RELIABILITY_OK', temp)
